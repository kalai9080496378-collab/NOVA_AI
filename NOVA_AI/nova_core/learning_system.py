def record_correction(
    user_prompt: str,
    corrected_response: str,
    rejected_response: Optional[str] = None,
    explanation: Optional[str] = None,
    category: str = "Correction",
    is_approved: bool = True,
    source: str = "user_correction",
    db_path: Optional[Path | str] = None,
) -> Dict[str, Any]:
    """
    Stores an explicitly approved user correction or demonstration example.
    Used for instant in-context few-shot learning and fine-tuning datasets.
    
    Args:
        user_prompt: The prompt or question that was answered incorrectly or sub-optimally.
        corrected_response: The verified correct answer provided by the user.
        rejected_response: The original incorrect answer generated by the assistant.
        explanation: Optional note explaining why the correction was made.
        category: 'Correction', 'Demonstration', 'DomainKnowledge'.
        is_approved: Whether this example is approved for retrieval and learning.
        source: 'user_correction' or 'direct_entry'.
        db_path: Optional SQLite database path override.
        
    Returns:
        Dict representing the learning example record.
    """
    clean_prompt = (user_prompt or "").strip()
    clean_corrected = (corrected_response or "").strip()

    if not clean_prompt:
        raise ValueError("User prompt cannot be empty.")
    if not clean_corrected:
        raise ValueError("Corrected response cannot be empty.")

    now = datetime.now(timezone.utc).isoformat()
    clean_rejected = rejected_response.strip() if rejected_response else None
    clean_explanation = explanation.strip() if explanation else None
    clean_cat = category.strip() if category else "Correction"
    appr_flag = 1 if is_approved else 0

    # Deduplication check: if exact user prompt already exists in learning_examples, update it
    check_sql = "SELECT id FROM learning_examples WHERE LOWER(user_prompt) = LOWER(?)"
    existing = fetch_one(check_sql, (clean_prompt,), db_path=db_path)

    if existing:
        ex_id = existing["id"]
        update_sql = """
            UPDATE learning_examples 
            SET corrected_response = ?, rejected_response = ?, explanation = ?, category = ?, is_approved = ?, updated_at = ?
            WHERE id = ?
        """
        execute_query(update_sql, (clean_corrected, clean_rejected, clean_explanation, clean_cat, appr_flag, now, ex_id), db_path=db_path)
        log_action("update_correction", f"Updated learning example #{ex_id}", status="success", db_path=db_path)
        return get_correction_by_id(ex_id, db_path=db_path) or {}

    insert_sql = """
        INSERT INTO learning_examples (category, user_prompt, rejected_response, corrected_response, explanation, is_approved, is_used_in_training, source, created_at, updated_at)
        VALUES (?, ?, ?, ?, ?, ?, 0, ?, ?, ?)
    """
    lid = execute_insert(
        insert_sql,
        (clean_cat, clean_prompt, clean_rejected, clean_corrected, clean_explanation, appr_flag, source, now, now),
        db_path=db_path,
    )
    log_action("record_correction", f"Recorded learning example #{lid} in '{clean_cat}'", status="success", db_path=db_path)

    return get_correction_by_id(lid, db_path=db_path) or {}


def get_correction_by_id(example_id: int, db_path: Optional[Path | str] = None) -> Optional[Dict[str, Any]]:
    """Retrieves a single learning example by its primary ID."""
    sql = "SELECT * FROM learning_examples WHERE id = ?"
    return fetch_one(sql, (example_id,), db_path=db_path)


def get_learning_examples(
    category: Optional[str] = None,
    only_approved: bool = True,
    search_query: Optional[str] = None,
    limit: int = 100,
    db_path: Optional[Path | str] = None,
) -> List[Dict[str, Any]]:
    """Retrieves stored learning examples with optional filters."""
    conditions = []
    params: List[Any] = []

    if only_approved:
        conditions.append("is_approved = 1")

    if category and category.lower() != "all":
        conditions.append("LOWER(category) = ?")
        params.append(category.strip().lower())

    if search_query and search_query.strip():
        term = f"%{search_query.strip()}%"
        conditions.append("(user_prompt LIKE ? OR corrected_response LIKE ? OR explanation LIKE ?)")
        params.extend([term, term, term])

    where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""
    sql = f"""
        SELECT * FROM learning_examples
        {where_clause}
        ORDER BY updated_at DESC, id DESC
        LIMIT ?
    """
    params.append(limit)
    return fetch_all(sql, tuple(params), db_path=db_path)


def delete_correction(example_id: int, db_path: Optional[Path | str] = None) -> bool:
    """Permanently deletes a learning example by ID."""
    existing = get_correction_by_id(example_id, db_path=db_path)
    if not existing:
        return False

    sql = "DELETE FROM learning_examples WHERE id = ?"
    affected = execute_query(sql, (example_id,), db_path=db_path)
    log_action("delete_correction", f"Deleted learning example #{example_id}", status="success", db_path=db_path)
    return affected > 0


