def check_memory_duplicate_or_conflict(
    candidate_content: str,
    category: str = "General",
    db_path: Optional[Path | str] = None,
) -> Dict[str, Any]:
    """
    Prevents duplicate knowledge and conflicting or unverified facts from being blindly accepted.
    
    Checks:
    1. Exact duplicate memory in SQLite.
    2. High token-overlap near-duplicate.
    3. Potential conflict within the same category.
    
    Returns:
        Dict:
            - is_duplicate (bool)
            - is_conflict (bool)
            - existing_id (int or None)
            - existing_content (str or None)
            - warning_message (str or None)
    """
    clean_candidate = candidate_content.strip()
    if not clean_candidate:
        return {"is_duplicate": False, "is_conflict": False, "warning_message": None}

    # Fetch existing memories
    from memory.memory_manager import get_all_memories
    existing_memories = get_all_memories(db_path=db_path)

    cand_tokens = _tokenize(clean_candidate)
    clean_lower = clean_candidate.lower()

    for m in existing_memories:
        m_lower = m["content"].lower().strip()
        # Exact match
        if clean_lower == m_lower:
            return {
                "is_duplicate": True,
                "is_conflict": False,
                "existing_id": m["id"],
                "existing_content": m["content"],
                "warning_message": f"Exact duplicate detected: Memory #{m['id']} already stores this information.",
            }

        # Substantial token overlap (> 85%)
        m_tokens = _tokenize(m["content"])
        if cand_tokens and m_tokens:
            overlap = len(cand_tokens.intersection(m_tokens)) / len(cand_tokens.union(m_tokens))
            if overlap > 0.85:
                return {
                    "is_duplicate": True,
                    "is_conflict": False,
                    "existing_id": m["id"],
                    "existing_content": m["content"],
                    "warning_message": f"Near duplicate ({int(overlap*100)}% match) of Memory #{m['id']}: \"{m['content']}\".",
                }

    return {"is_duplicate": False, "is_conflict": False, "warning_message": None}


