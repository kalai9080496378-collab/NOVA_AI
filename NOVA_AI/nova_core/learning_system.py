def export_memories_json(db_path: Optional[Path | str] = None) -> str:
    """Exports all stored memories as formatted JSON for user sovereignty."""
    from memory.memory_manager import get_all_memories
    memories = get_all_memories(db_path=db_path)
    return json.dumps({"count": len(memories), "memories": memories}, indent=2)


def export_memories_csv(db_path: Optional[Path | str] = None) -> str:
    """Exports all stored memories as CSV."""
    import csv
    import io
    from memory.memory_manager import get_all_memories
    memories = get_all_memories(db_path=db_path)
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["id", "category", "content", "created_at", "updated_at"])
    for m in memories:
        writer.writerow([m["id"], m["category"], m["content"], m["created_at"], m["updated_at"]])
    return output.getvalue()


def get_learning_system_metrics(db_path: Optional[Path | str] = None) -> Dict[str, Any]:
    """
    Aggregates metrics across the 4 separated knowledge stores:
    1. Conversation History (conversations)
    2. Personal Memory (memories)
    3. Document Knowledge Base (documents & document_chunks)
    4. Training & Correction Datasets (learning_examples & training_datasets)
    """
    from memory.memory_manager import get_all_memories
    from modules.document_assistant import get_documents

    # 1. Memories
    mems = get_all_memories(db_path=db_path)
    approved_memories_count = len(mems)

    # 2. Documents
    docs = get_documents(db_path=db_path)
    indexed_docs_count = len(docs)
    total_doc_words = sum(d.get("word_count", 0) for d in docs)

    # Document chunks count
    chunks_row = fetch_one("SELECT COUNT(*) as c FROM document_chunks", (), db_path=db_path) or {}
    total_chunks = chunks_row.get("c", 0)

    # 3. Feedback & Corrections
    fb_summary = get_feedback_summary(db_path=db_path)
    corrections = get_learning_examples(only_approved=True, limit=500, db_path=db_path)
    approved_corrections_count = len(corrections)

    # 4. Datasets
    ds_row = fetch_one("SELECT COUNT(*) as c, SUM(total_samples) as s FROM training_datasets", (), db_path=db_path) or {}
    total_datasets = ds_row.get("c") or 0
    total_dataset_samples = ds_row.get("s") or 0

    # 5. Active Model in registry
    model_row = fetch_one("SELECT * FROM model_registry WHERE status = 'active' ORDER BY updated_at DESC LIMIT 1", (), db_path=db_path)
    if not model_row:
        model_row = {
            "id": "model_v1_base",
            "version_tag": "v1.0.0-base",
            "provider": "gemini",
            "base_model": "gemini-1.5-flash",
            "eval_score": 85.0,
            "status": "active",
        }

    # 6. Last knowledge update
    last_up_sql = """
        SELECT MAX(ts) as last_update FROM (
            SELECT MAX(updated_at) as ts FROM memories
            UNION ALL
            SELECT MAX(created_at) as ts FROM documents
            UNION ALL
            SELECT MAX(updated_at) as ts FROM learning_examples
        )
    """
    last_row = fetch_one(last_up_sql, (), db_path=db_path) or {}
    last_update = last_row.get("last_update") or "No updates recorded yet"

    return {
        "approved_memories": approved_memories_count,
        "indexed_documents": indexed_docs_count,
        "document_chunks": total_chunks,
        "total_document_words": total_doc_words,
        "feedback_summary": fb_summary,
        "approved_corrections": approved_corrections_count,
        "training_datasets_count": total_datasets,
        "training_dataset_samples": total_dataset_samples,
        "current_model": model_row,
        "last_knowledge_update": last_update[:19].replace("T", " ") if "T" in str(last_update) else str(last_update),
    }
