# =============================================================================

def retrieve_relevant_corrections(
    query: str,
    threshold: float = 0.25,
    limit: int = 3,
    db_path: Optional[Path | str] = None,
) -> List[Dict[str, Any]]:
    """
    Searches stored approved learning examples for relevant demonstrations to inject into
    the current query context. Uses normalized token-overlap similarity.
    
    Args:
        query: Incoming user prompt.
        threshold: Minimum Jaccard token similarity score (0.0 to 1.0).
        limit: Max number of relevant examples to return.
        db_path: Optional SQLite database path override.
        
    Returns:
        List of matching learning examples with similarity score.
    """
    if not query or not query.strip():
        return []

    examples = get_learning_examples(only_approved=True, limit=200, db_path=db_path)
    if not examples:
        return []

    query_tokens = _tokenize(query)
    if not query_tokens:
        return []

    scored_results = []
    for ex in examples:
        ex_tokens = _tokenize(ex["user_prompt"])
        if not ex_tokens:
            continue

        # Compute Jaccard token similarity
        intersection = query_tokens.intersection(ex_tokens)
        union = query_tokens.union(ex_tokens)
        score = len(intersection) / len(union) if union else 0.0

        # Exact substring or substring inclusion bonus
        clean_q = query.strip().lower()
        clean_p = ex["user_prompt"].strip().lower()
        if clean_q == clean_p:
            score = 1.0
        elif clean_q in clean_p or clean_p in clean_q:
            score = max(score, 0.75)

        if score >= threshold:
            res = dict(ex)
            res["similarity"] = round(score, 3)
            scored_results.append(res)

    scored_results.sort(key=lambda x: x["similarity"], reverse=True)
    return scored_results[:limit]


def _tokenize(text: str) -> set:
    """Extracts lowercase alpha-numeric token set, ignoring common stop words."""
    stop_words = {
        "a", "an", "the", "in", "on", "at", "to", "for", "with", "by", "of",
        "is", "are", "was", "were", "be", "been", "it", "this", "that", "what",
        "how", "can", "you", "please", "me", "i", "do", "does", "and", "or",
    }
    words = re.findall(r"\b[a-zA-Z0-9_\-]{2,}\b", text.lower())
    return {w for w in words if w not in stop_words}


