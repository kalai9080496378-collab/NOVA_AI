def record_message_feedback(
    conversation_id: str,
    rating: str,
    message_id: Optional[int] = None,
    feedback_text: Optional[str] = None,
    is_approved_for_training: bool = False,
    db_path: Optional[Path | str] = None,
) -> Dict[str, Any]:
    """
    Records explicit user rating (thumbs_up or thumbs_down) for an assistant response turn.
    
    Args:
        conversation_id: Chat thread ID.
        rating: 'thumbs_up' or 'thumbs_down'.
        message_id: Optional database ID of the conversation turn.
        feedback_text: Optional comment or correction explanation from the user.
        is_approved_for_training: Explicit user consent to use this feedback for training.
        db_path: Optional SQLite database path override.
        
    Returns:
        Dict of the recorded feedback entry.
    """
    clean_rating = (rating or "").strip().lower()
    if clean_rating not in {"thumbs_up", "thumbs_down"}:
        raise ValueError("Feedback rating must be either 'thumbs_up' or 'thumbs_down'.")

    now = datetime.now(timezone.utc).isoformat()
    clean_text = feedback_text.strip() if feedback_text else None
    consent_flag = 1 if is_approved_for_training else 0

    sql = """
        INSERT INTO message_feedback (message_id, conversation_id, rating, feedback_text, is_approved_for_training, created_at)
        VALUES (?, ?, ?, ?, ?, ?)
    """
    fid = execute_insert(sql, (message_id, conversation_id, clean_rating, clean_text, consent_flag, now), db_path=db_path)
    log_action("record_feedback", f"Recorded {clean_rating} feedback #{fid} for conv '{conversation_id}'", status="success", db_path=db_path)

    return {
        "id": fid,
        "message_id": message_id,
        "conversation_id": conversation_id,
        "rating": clean_rating,
        "feedback_text": clean_text,
        "is_approved_for_training": consent_flag,
        "created_at": now,
    }


def get_feedback_summary(db_path: Optional[Path | str] = None) -> Dict[str, Any]:
    """Retrieves aggregate feedback counts and consent statistics."""
    sql = """
        SELECT 
            COUNT(*) as total,
            SUM(CASE WHEN rating = 'thumbs_up' THEN 1 ELSE 0 END) as thumbs_up,
            SUM(CASE WHEN rating = 'thumbs_down' THEN 1 ELSE 0 END) as thumbs_down,
            SUM(CASE WHEN is_approved_for_training = 1 THEN 1 ELSE 0 END) as approved_for_training
        FROM message_feedback
    """
    row = fetch_one(sql, (), db_path=db_path) or {}
    total = row.get("total") or 0
    up = row.get("thumbs_up") or 0
    down = row.get("thumbs_down") or 0
    approved = row.get("approved_for_training") or 0
    ratio = round((up / total * 100), 1) if total > 0 else 0.0

    return {
        "total_feedback": total,
        "thumbs_up": up,
        "thumbs_down": down,
        "approved_for_training": approved,
        "satisfaction_rate": ratio,
    }


